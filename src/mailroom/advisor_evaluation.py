"""Measures the model advisor on the same synthetic documents as `make evaluate`.

The question is not whether the model classifies well on its own. It is whether, as a second
opinion that can only send automatic filings to review, it catches wrong automatic filings
without sending too many correct ones to a person.

Answers are cached by text hash, so a run stopped by the free tier's daily limit continues
where it left off. Only synthetic documents generated here are ever sent.
"""

import argparse
import hashlib
import json
import random
import time
from collections import Counter
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

from mailroom import advisor
from mailroom.evaluation import (
    DEFAULT_DOCUMENTS,
    DEFAULT_MATTERS,
    DEFAULT_SEED,
    Outcome,
    evaluate_one,
    generate_documents,
    generate_matters,
)
from mailroom.matcher import Thresholds
from mailroom.models import DocumentType, State

Ask = Callable[[str], advisor.Suggestion]


@dataclass(frozen=True)
class Judged:
    outcome: Outcome
    suggestion: advisor.Suggestion


class CachedAsk:
    """Answers from earlier runs are reused. Failures are not cached, so they are retried."""

    def __init__(self, ask: Ask, path: Path, pause_seconds: float) -> None:
        self._ask = ask
        self._path = path
        self._pause_seconds = pause_seconds
        self._answers: dict[str, str] = json.loads(path.read_text()) if path.exists() else {}
        self.calls = 0

    def __call__(self, text: str, model: str) -> advisor.Suggestion:
        key = hashlib.sha256(f"{model}\n{text}".encode()).hexdigest()
        if key in self._answers:
            return advisor.Suggestion(model, DocumentType(self._answers[key]))
        if self.calls:
            time.sleep(self._pause_seconds)
        self.calls += 1
        suggestion = self._ask(text)
        if suggestion.document_type is not None:
            self._answers[key] = suggestion.document_type.value
            self._path.parent.mkdir(parents=True, exist_ok=True)
            self._path.write_text(json.dumps(self._answers, indent=0, sort_keys=True))
        return suggestion


def judge(outcomes: Sequence[Outcome], ask: Callable[[str], advisor.Suggestion]) -> list[Judged]:
    judged = []
    for outcome in outcomes:
        suggestion = ask(outcome.document.text)
        judged.append(Judged(outcome, suggestion))
        if suggestion.reason == "circuit_open":
            # The daily limit is spent. Stop asking, and report on what was answered.
            break
    return judged


def _ratio(numerator: int, denominator: int) -> str:
    return f"{numerator / denominator:.1%}" if denominator else "n/a"


def _model_type(item: Judged) -> DocumentType | None:
    return item.suggestion.document_type


def _rules_type(item: Judged) -> DocumentType:
    return item.outcome.predicted_type


def _true_type(item: Judged) -> DocumentType:
    return item.outcome.document.true_type


def build_report(model: str, total: int, judged: Sequence[Judged]) -> str:
    answered = [item for item in judged if _model_type(item) is not None]
    reasons = Counter(item.suggestion.reason for item in judged if item.suggestion.reason)
    model_right = sum(_model_type(item) == _true_type(item) for item in answered)
    rules_right = sum(_rules_type(item) == _true_type(item) for item in answered)
    agreed = sum(_model_type(item) == _rules_type(item) for item in answered)

    automatic = [item for item in answered if item.outcome.state is State.READY_TO_FILE]
    blocked = [item for item in automatic if _model_type(item) != _rules_type(item)]
    wrong_type = [item for item in automatic if _rules_type(item) != _true_type(item)]
    caught = [item for item in wrong_type if item in blocked]
    needless = [item for item in blocked if item not in wrong_type]

    unanswered = ", ".join(f"{name} {count}" for name, count in sorted(reasons.items()))
    count = len(answered)
    lines = [
        "# Model advisor evaluation",
        "",
        "Generated by `make evaluate-advisor`. Do not edit by hand.",
        "",
        f"Model `{model}`. Same synthetic documents as [EVALUATION.md](EVALUATION.md): seed "
        f"{DEFAULT_SEED}, {total} documents.",
        "",
        f"Answered: {count} of {total}." + (f" Not answered: {unanswered}." if reasons else ""),
        "",
        "## Classification, on answered documents",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Model accuracy | {_ratio(model_right, count)} ({model_right} of {count}) |",
        f"| Rules accuracy | {_ratio(rules_right, count)} ({rules_right} of {count}) |",
        f"| Model agrees with rules | {_ratio(agreed, count)} |",
        "",
        "## Effect on automatic filing",
        "",
        "The model can only send an automatic filing to review. These rows count answered",
        "documents the rules would have filed automatically.",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Automatic filings without the model | {len(automatic)} |",
        f"| Of those, filed with the wrong document type | {len(wrong_type)} |",
        f"| Wrong-type filings the model stopped | {len(caught)} of {len(wrong_type)} |",
        f"| Correct filings the model sent to review | {len(needless)} |",
        f"| Automatic filings with the model | {len(automatic) - len(blocked)} |",
        "",
        "## Limitations",
        "",
        "- **Synthetic data only**, generated from the same templates the rules were written for,",
        "  so this flatters the rules and says little about real documents.",
        "- **A model's answers can change between runs and versions.** Cached answers make a rerun",
        "  repeat the same result; delete the cache to ask again.",
        "- **Free-tier answers may be used by Google** to improve its products. Nothing but these",
        "  generated documents was sent.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path(".cache/advisor-answers.json"))
    parser.add_argument("--pause", type=float, default=6.0, help="seconds between new requests")
    arguments = parser.parse_args()

    configured = advisor.from_settings()
    if configured is None:
        raise SystemExit("Set ADVISOR=gemini, ADVISOR_SYNTHETIC_DATA_ONLY=true and GEMINI_API_KEY")
    rng = random.Random(DEFAULT_SEED)
    matters = generate_matters(rng, DEFAULT_MATTERS)
    documents = generate_documents(rng, matters, DEFAULT_DOCUMENTS)
    outcomes = [evaluate_one(document, matters, Thresholds()) for document in documents]

    advisor.ADVISOR = configured

    def ask(text: str) -> advisor.Suggestion:
        return advisor.suggest(text) or advisor.Suggestion(configured.model, None, "off")

    cached = CachedAsk(ask, arguments.cache, arguments.pause)
    judged = judge(outcomes, lambda text: cached(text, configured.model))
    print(build_report(configured.model, len(outcomes), judged), end="")


if __name__ == "__main__":
    main()
